export function localizedName(item, lang) {
  if (!item) return '';
  return lang === 'en' ? item.nameEn || '' : item.nameKn || item.nameEn || '';
}

export function localizedTitle(day, lang) {
  if (!day) return '';
  return lang === 'en' ? day.titleEn || '' : day.titleKn || day.titleEn || '';
}

export function localizedSteps(exercise, lang) {
  return (exercise?.steps || [])
    .map((step) => ({
      main: lang === 'en' ? step.en || '' : step.kn || step.en || '',
      sub: lang === 'kn' ? step.en || '' : '',
    }))
    .filter((step) => step.main);
}

