export function createT(lang) {
  const table = UI[lang] || UI.kn;
  return function t(key, vars) {
    let value = table[key];
    if (value == null) value = lang === 'en' ? key : UI.kn[key] ?? key;
    if (vars) {
      for (const [k, v] of Object.entries(vars)) {
        value = value.replaceAll(`{${k}}`, String(v));
      }
    }
    return value;
  };
}

// Plan content is stored bilingually so the editor can maintain both languages.
